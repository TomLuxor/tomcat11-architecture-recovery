// RQ3 (step 7): prepares the independent classification of the messages absent at both mapping levels.
// Usage: node analysis/rq3_sheet.js <author> [<author> ...]   (needs the jQAssistant server, like reflexion.js)
// Writes review/rq3_facts.md (facts per message), review/rq3_rules.csv (classification by the codebook rules),
// an empty review/rq3_<author>.csv per author (unless it exists) and output/rq3_groups.csv (messages per group).
const fs = require('fs');
const path = require('path');
const neo4j = require('neo4j-driver');
const { parseCsv, serializeCsv } = require('./lib/csv');
const { typesFor } = require('./lib/reflexion');
const { selectAbsences, similarNames, describeFacts, classifyByRules } = require('./lib/rq3');

const here = __dirname;
const read = f => parseCsv(fs.readFileSync(path.join(here, f), 'utf8'));

async function main() {
  const authors = process.argv.slice(2);
  const { toClassify, counts } = selectAbsences(read('output/reflexion_messages.csv'));
  const mapping = new Map(read('output/mapping.csv').map(r => [r.participant, r]));
  const both = label => [...new Set(['interface', 'implementation'].flatMap(l => typesFor(mapping.get(label), l).types))];
  const query = fs.readFileSync(path.join(here, 'queries', 'absence_facts.cypher'), 'utf8');

  const driver = neo4j.driver(process.env.NEO4J_URI || 'bolt://localhost:7687', neo4j.auth.basic('neo4j', 'neo4j'));
  const session = driver.session();
  const lines = ['# RQ3 facts per absent message', '',
    'Generated by `analysis/rq3_sheet.js` from the source model. See `rq3_instructions.md` for the categories.', '',
    '| Message | Arrow in the diagram | Facts from the code |', '|---|---|---|'];
  const byRules = [];
  try {
    for (const m of toClassify) {
      const name = m.kind === 'create' ? '<init>' : m.message.split('(')[0].trim();
      const to = both(m.to);
      const factsFor = async n => (await session.run(query, { from: both(m.from), to, name: n.toLowerCase() })).records[0].toObject();
      const facts = await factsFor(name);
      byRules.push({ id: m.id, from: m.from, to: m.to, message: m.message, category: classifyByRules(facts, name),
        reason: 'codebook rules applied to the facts (lib/rq3.js, classifyByRules)' });
      let text = describeFacts(facts, name, to);
      // A misspelled name in the diagram: also show the facts for the closest existing method.
      const [similar] = facts.declaredBy.length ? [] : similarNames(name, facts.methods);
      if (similar) text += ` With the existing name ${similar}(): ${describeFacts(await factsFor(similar), similar, to)}`;
      const arrow = `${m.from} → ${m.to}: ${m.kind === 'create' ? 'creates' : m.message || '(no name)'}`;
      lines.push(`| \`${m.id}\` | ${arrow.replace(/\|/g, '\\|')} | ${text.replace(/\|/g, '\\|')} |`);
    }
  } finally {
    await session.close();
    await driver.close();
  }
  fs.writeFileSync(path.join(here, 'review', 'rq3_facts.md'), lines.join('\n') + '\n');
  fs.writeFileSync(path.join(here, 'review', 'rq3_rules.csv'),
    serializeCsv(byRules, ['id', 'from', 'to', 'message', 'category', 'reason']));
  const categories = new Map();
  for (const r of byRules) {
    if (!categories.has(r.category)) categories.set(r.category, { category: r.category, messages: 0, example: `${r.id} ${r.from} -> ${r.to}` });
    categories.get(r.category).messages++;
  }
  fs.writeFileSync(path.join(here, 'output', 'rq3_categories.csv'),
    serializeCsv([...categories.values()].sort((a, b) => b.messages - a.messages), ['category', 'messages', 'example']));
  for (const author of authors) {
    const file = path.join(here, 'review', `rq3_${author}.csv`);
    if (fs.existsSync(file)) { console.warn(`${file} exists, left unchanged`); continue; }
    fs.writeFileSync(file, serializeCsv(toClassify.map(m => ({ id: m.id, from: m.from, to: m.to, message: m.message })),
      ['id', 'from', 'to', 'message', 'category', 'reason']));
  }
  fs.writeFileSync(path.join(here, 'output', 'rq3_groups.csv'),
    serializeCsv(Object.entries(counts).map(([group, messages]) => ({ group, messages })), ['group', 'messages']));
  console.table(counts);
}

main().catch(e => { console.error(e.message); process.exit(1); });
